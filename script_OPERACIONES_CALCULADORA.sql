CREATE TABLE OPERACIONES_CALCULADORA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO1 NUMBER(20,4),
    NUMERO2 NUMBER(20,4),
    OPERADOR VARCHAR2(5),
    RESULTADO NUMBER(30,10),
    FECHA_OPERACION DATE DEFAULT SYSDATE,

    CONSTRAINT PK_OPERACIONES_CALCULADORA
        PRIMARY KEY (ID)
);

COMMIT;

-- SP procedimiento almacenado.
CREATE OR REPLACE PROCEDURE INSERTAR_OPERACION (
    P_NUMERO1    IN NUMBER,
    P_NUMERO2    IN NUMBER,
    P_OPERADOR   IN VARCHAR2,
    P_RESULTADO  IN NUMBER
)
AS
BEGIN

    INSERT INTO OPERACIONES_CALCULADORA
    (
        NUMERO1,
        NUMERO2,
        OPERADOR,
        RESULTADO
    )
    VALUES
    (
        P_NUMERO1,
        P_NUMERO2,
        P_OPERADOR,
        P_RESULTADO
    );

    COMMIT;

END;
/

COMMIT;

-- Para comprobar los datos: 
SELECT ID, NUMERO1, NUMERO2, OPERADOR, RESULTADO, FECHA_OPERACION
FROM OPERACIONES_CALCULADORA ORDER BY ID DESC;  

